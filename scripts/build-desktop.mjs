// Builds desktop/plugin.js from desktop-src/plugin.src.js and data/icons.json.
// Usage: node scripts/build-desktop.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const data = JSON.parse(readFileSync(join(root, 'data/icons.json'), 'utf8'))
for (const key of ['asset_base', 'viewer_url']) {
  if (!/^https:\/\/[^"'<>\s#?]+$/.test(data[key] || '')) throw new Error(`${key} must be a plain https URL`)
}

const icons = data.icons.map(icon => {
  if (!/^[a-z0-9-]{1,40}$/.test(icon.id)) throw new Error(`Bad icon id: ${icon.id}`)
  return { id: icon.id, title: icon.title, category: icon.category, description: icon.description, tags: icon.tags || [] }
})

const plugin = readFileSync(join(root, 'desktop-src/plugin.src.js'), 'utf8')
  .replace('__ICONS__', () => JSON.stringify(icons, null, 1))
  .replace('__ASSET_BASE__', () => JSON.stringify(data.asset_base))
  .replace('__VIEWER_URL__', () => JSON.stringify(data.viewer_url))

writeFileSync(join(root, 'desktop/plugin.js'), `// GENERATED by scripts/build-desktop.mjs from desktop-src/plugin.src.js. Do not edit.\n${plugin}`)
console.log(`Built desktop/plugin.js (${icons.length} icons)`)
